def _first_full_design_quarter(q: pl.DataFrame) -> dict | None:
    """First complete quarter whose three months all have the full draw design ([signers].recent_first_month)."""
    from . import config
    first = config.load()["signers"]["recent_first_month"]
    y, m = int(first[:4]), int(first[5:7])
    qn = (m - 1) // 3 + 1
    if m != 3 * (qn - 1) + 1:  # the design starts mid-quarter: take the next quarter
        y, qn = (y + 1, 1) if qn == 4 else (y, qn + 1)
    r = q.filter((pl.col("quarter") >= f"{y}-Q{qn}") & (pl.col("months") == 3)).sort("quarter")
    return r.row(0, named=True) if r.height else None


def _ci(v, lo, hi, unit="") -> str:
    if v is None:
        return "n/a"
    if lo is None or hi is None:
        return fmt(v, unit)
    return f"{fmt(v, unit)} ({fmt(lo, unit)} to {fmt(hi, unit)})"


def _row(df: pl.DataFrame, **eq) -> dict | None:
    f = df
    for k, v in eq.items():
        f = f.filter(pl.col(k) == v)
    return f.row(0, named=True) if f.height else None


