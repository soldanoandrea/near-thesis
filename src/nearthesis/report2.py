def _model_c(am, mcfg) -> list[str]:
    L = ["## (c) Adoption model on organic activity", "",
         "**Assumptions.** Series: organic daily and monthly active signers and organic transactions per day from the "
         "bot-vs-human decomposition (complete months with the full 200-draw design, from 2024-11; trailing 3-month "
         "means, because a month with no organic draw estimates 0, which a log model cannot use), and NEAR Intents "
         "monthly volume "
         "(DefiLlama) as a comparison. Models: log-linear trend, logistic S-curve (K profiled over a grid; r < 0 gives a "
         "declining S-curve), naive random walk. Rolling-origin backtest from "
         f"{mcfg['adoption_min_train']} months of training, horizons {mcfg['adoption_backtest_horizons']} months; error = "
         "|log forecast - log actual|. Forecast ranges: residual bootstrap "
         f"({mcfg['adoption_bootstrap']} draws), 5th-95th percentile.", ""]
    if not am:
        return L + ["Organic series not available.", ""]
    f = am["model_adoption_fits"]
    L.append(table(["Series", "Model", "Months", "Growth /month (log-linear)", "K (logistic)", "r (logistic)", "Residual sd (log)"],
                   [[r["series"], r["model"], f"{r['first_month']} to {r['last_month']}", fmt(r["growth_per_month"], "ratio"),
                     fmt(r["K"]), fmt(r["r"]), fmt(r["sigma_log"])] for r in f.iter_rows(named=True)]))
