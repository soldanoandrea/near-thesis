def _model_d(inp, ym, mcfg) -> list[str]:
    L = ["## (d) Staking yield and real yield", "",
         "**Definitions.** Gross staker yield = issuance x (1 - treasury share) / staking ratio; net = gross x (1 - "
         "commission); float dilution = issuance - burn - buybacks; real staker yield = (1 + net) / (1 + float dilution) "
         "- 1 (change in a staker's share of the float); non-staker real yield = 1 / (1 + float dilution) - 1. Commission "
         f"is not measured here: {mcfg['commissions']} are shown.", ""]
    h = ym["model_yields_history"].filter(pl.col("commission_assumed") == 0.05)
    L.append(table(["Period", "Issuance", "Burn", "Buybacks", "Staking ratio", "Gross staker yield", "Net (5% commission)",
                    "Float dilution", "Real staker yield", "Non-staker real yield"],
                   [[r["period"], fmt(r["issuance_rate"], "ratio"), fmt(r["burn_rate"], "ratio"), fmt(r["buyback_rate"], "ratio"),
                     fmt(r["staking_ratio"], "ratio"), fmt(r["gross_staker_yield"], "ratio"), fmt(r["net_staker_yield"], "ratio"),
                     fmt(r["float_dilution"], "ratio"), fmt(r["real_staker_yield"], "ratio"),
                     fmt(r["real_non_staker_yield"], "ratio")] for r in h.iter_rows(named=True)]))
    L.append("")
    g = ym["model_yields_scenarios"].filter(pl.col("commission") == 0.05).sort(["policy", "buyback_rate", "staking_ratio"])
    L.append(table(["Policy (steady state)", "Buybacks", "Staking ratio", "Gross staker yield", "Net (5%)", "Float dilution",
                    "Real staker yield", "Non-staker real yield"],
                   [[r["policy"], fmt(r["buyback_rate"], "ratio"), fmt(r["staking_ratio"], "ratio"),
                     fmt(r["gross_staker_yield"], "ratio"), fmt(r["net_staker_yield"], "ratio"),
                     fmt(r["float_dilution"], "ratio"), fmt(r["real_staker_yield"], "ratio"),
                     fmt(r["real_non_staker_yield"], "ratio")] for r in g.iter_rows(named=True)]))
    L += ["", "**Falsifier of the bullish case**: the real yield of a non-staker (holder dilution net of burn and buybacks) "
          "stays below -2% per year; i.e. value accrual does not offset dilution."]
    r = ym["model_yields_history"].filter((pl.col("period") == "last 365 days") & (pl.col("commission_assumed") == 0.05))
