def _model_a(inp, sm, mcfg) -> list[str]:
    L = ["## (a) Supply and value-accrual scenarios: 2.5% vs HSP-029 (1.6%)", "",
         "**Assumptions.** Monthly recursion: issuance = supply x cap x realized/cap; burn = supply x burn rate, growing "
         "with fees; buybacks = supply x buyback yield, growing with Intents revenue relative to price (constant price "
         "here). Bought-back NEAR is held, not burned (DefiLlama adapter; HSP-029 text), so it reduces the float, not "
         f"total supply. HSP-029 ({inp.get('hsp029_url', 'gov.near.org/t/42644')}, status \"{inp.get('hsp029_status', 'n/a')}\" "
         f"at the {inp.get('hsp029_snapshot_utc', 'n/a')} snapshot; the vote was reported to close 2026-11-02): cap(t) = 2.5% - 0.9% x min(t, 24)/24 after activation one full quarter after "
         "ratification, then validators must adopt the upgrade; we model activation at month "
         f"{' and '.join(str(a) for a in mcfg['hsp029_activation_months'])}.", "",
         f"**Ranges.** Fee growth per year: {mcfg['fee_growth']}; Intents revenue growth per year (NEAR terms): "
         f"{mcfg['revenue_growth']}; horizons {mcfg['horizons_years']} years.", ""]
    st = sm["model_supply_scenarios"].filter(pl.col("horizon_years").is_in([1, 3, 5])).sort(["scenario", "horizon_years"])
    L.append(table(["Scenario", "Years", "Total supply", "Float", "Supply growth /yr", "Float growth /yr",
                    "Issuance in final year", "Burn + buybacks in final year", "Offsets cover issuance"],
                   [[r["scenario"], r["horizon_years"], fmt(r["total_supply"], "NEAR"), fmt(r["float_supply"], "NEAR"),
                     fmt(r["supply_growth_cagr"], "ratio"), fmt(r["float_growth_cagr"], "ratio"),
                     fmt(r["year_issuance_rate"], "ratio"), fmt(r["year_offset_rate"], "ratio"),
                     "yes" if r["offsets_cover_issuance"] else "no"] for r in st.iter_rows(named=True)]))
    L.append("")
    g = sm["model_net_zero_grid"].sort(["issuance_rate", "price_usd", "take_rate"], descending=[True, False, False])
    L += ["Net-zero threshold: Intents captured revenue (and volume at a take rate) at which burn + buybacks equal "
          "issuance, all captured revenue used for buybacks:", ""]
    L.append(table(["Issuance", "NEAR price", "Take rate", "Revenue needed /yr", "x current revenue", "Volume needed /yr",
                    "x current volume"],
                   [[fmt(r["issuance_rate"], "ratio"), fmt(r["price_usd"], "USD"), f"{r['take_rate'] * 1e4:.2f} bp",
                     fmt(r["required_revenue_usd"], "USD"), fmt(r["multiple_of_current_revenue"]),
                     fmt(r["required_volume_usd"], "USD"), fmt(r["multiple_of_current_volume"])]
                    for r in g.iter_rows(named=True)]))
    base = _row(sm["model_net_zero_grid"], issuance_rate=sorted(sm["model_net_zero_grid"]["issuance_rate"].unique().to_list())[-1],
                price_usd=sorted(sm["model_net_zero_grid"]["price_usd"].unique().to_list())[1],
                take_rate=sorted(sm["model_net_zero_grid"]["take_rate"].unique().to_list())[1])
    sq = _row(sm["model_supply_scenarios"], scenario="status_quo/base", horizon_years=1)
    if inp.get("intents_onchain_one_sided_to_defillama"):
        L += ["", f"Volumes in this grid are DefiLlama volumes. The on-chain check (Q2) finds public one-sided volume at "
              f"{fmt(inp['intents_onchain_one_sided_to_defillama'], 'ratio')} of DefiLlama's figure. That changes the "
              "absolute volumes (and makes the on-chain take rate higher by the inverse ratio) but not the multiples: at "
              "a constant take rate, the volume multiple equals the multiple of captured revenue, and captured revenue "
              "reconciles with on-chain flows (Q4)."]
    L += ["", "**Falsifier of the bullish case** (PIANO.md Q4): net float dilution after buybacks stays above 2% per year "
          "and the net-zero threshold needs more than 10x current volume at the current take rate."]
    if base and sq:
        a = sq["year_net_float_dilution"] > 0.02
        b = base["multiple_of_current_volume"] > 10
        L.append(f"Current reading: float dilution in year 1 (status quo, base) {fmt(sq['year_net_float_dilution'], 'ratio')} "
                 f"({'above' if a else 'not above'} 2%); threshold {fmt(base['multiple_of_current_volume'])}x current volume "
                 f"({'above' if b else 'not above'} 10x) on the 90-day run rate"
                 + (f"; {fmt(base['required_revenue_usd'] / inp['intents_revenue_365d'])}x against trailing 365-day revenue"
                    if inp.get("intents_revenue_365d") else "") + ". The falsifier "
                 + ("is met: the supply side does not support the bullish case at current activity." if a and b else
                    "is not met (it needs both conditions); "
                    + ("the dilution leg holds." if a else "the threshold leg holds." if b else "neither leg holds.")))
    L.append("")
    return L


