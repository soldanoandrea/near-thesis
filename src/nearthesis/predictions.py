"""Falsifiable predictions (one per key question of PIANO.md), with thresholds computed from the committed data.

Every threshold is a number the pipeline computes from data/processed at the snapshot (a current level, the lower
bound of its 90% interval, or the lowest level of the last four quarters); none is typed by hand. The rows go to
data/processed/predictions.csv and thesis/falsifiers.md (both generated by `make reproduce`); the sha256 of the CSV
is printed in the markdown so later edits are detectable.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

import polars as pl

from . import io
from .metrics import _d, full_wsum, ratio
from .transform.daily import series

SHORT, LONG = "2027-04-30", "2027-10-31"


def build(*, raw: Path, daily: pl.DataFrame, org: dict, led: dict, dev: dict, mm: dict, am: dict,
          as_of: str) -> pl.DataFrame:
    end = _d(as_of)
    rows = []

    def add(pid, q, claim, metric, comparator, threshold, unit, date, current, window, check, basis):
        rows.append({"id": pid, "question": q, "bullish_claim": claim, "metric": metric, "comparator": comparator,
                     "threshold": threshold, "unit": unit, "check_date": date, "current_value": current,
                     "current_window": window, "how_to_check": check, "threshold_basis": basis})

    if org:
        q = org["quarterly"].filter(pl.col("months") == 3).sort("quarter")
        if q.height:
            lq = q.row(-1, named=True)
            add("P1", "Q1", "Organic (human-like, non-incentivized) usage stops shrinking",
                "Organic monthly active signers, mean of 2027-07..2027-09 (organic_quarterly.csv, quarter 2027-Q3)",
                ">=", lq["mas_organic_p05"], "count", LONG, lq["mas_organic"], lq["quarter"],
                "make refresh && make build; read organic_quarterly.csv", f"lower bound of the 90% CI of {lq['quarter']}")
    vol = series(daily, "near", "intents_volume_usd", "defillama")
    v90 = full_wsum(vol, end, 90)
    add("P2", "Q2", "NEAR Intents volume keeps growing (no two-quarter decline)",
        "NEAR Intents volume, 90 days to 2027-04-30 (DefiLlama summary/dexs/near-intents)", ">=", v90, "USD", SHORT,
        v90, f"90 days to {as_of}", "make refresh; sum intents_volume_usd over the 90 days", "current 90-day volume")
    rc = io.read_csv(raw / "fastnear_tx" / "monthly_receiver_counts.csv").filter(
        pl.col("account_id") == "v1.signer").with_columns(pl.col("txs_count").cast(pl.Int64)).sort("month")
    last_full = rc.filter(pl.col("month") < as_of[:7])
    if last_full.height:
        r = last_full.row(-1, named=True)
        add("P3", "Q3", "Chain Signatures (the agent / chain-abstraction rail) usage grows",
            "Transactions in which v1.signer receives a receipt, September 2027 (FastNear census)", ">=",
            float(r["txs_count"]), "count", LONG, float(r["txs_count"]), r["month"],
            "make refresh; monthly_receiver_counts.csv, v1.signer", f"census count of {r['month']}")
    if led:
        rr = led["revenue_reconciliation"].filter(pl.col("month") < as_of[:7]).sort("month").tail(6)
        if rr.height == 6:
            add("P4", "Q4", "Value capture for holders grows: more Intents revenue reaches the buyback wallets",
                "Captured Intents revenue rebuilt on-chain (USD), 2026-11..2027-04 (ledger_revenue_reconciliation.csv)",
                ">=", float(rr["usd_onchain"].sum()), "USD", SHORT, float(rr["usd_onchain"].sum()),
                f"{rr['month'][0]} to {rr['month'][-1]}", "make refresh; sum usd_onchain over the six months",
                "previous six complete months")
    rev = series(daily, "near", "intents_revenue_usd", "defillama")
    tr = ratio(full_wsum(rev, end, 90), v90)
    add("P5", "Q5", "Fees are not competed away as volume grows",
        "NEAR Intents captured revenue / volume, 90 days to 2027-04-30 (DefiLlama)", ">=", tr * 0.8 if tr else None,
        "bp", SHORT, tr, f"90 days to {as_of}", "make refresh; intents_revenue_usd / intents_volume_usd",
        "80% of the current 90-day take rate (PIANO.md Q5 falsifier: take rate shrinking)")
    st = dev.get("dev_ecosystem_share_quarterly") if dev else None
    if st is not None:
        n = st.filter(pl.col("ecosystem") == "near").drop_nulls("near_to_peer_set").sort("quarter").tail(4)
        if n.height:
            add("P6", "Q6", "NEAR holds its developer base relative to peer chains",
                "NEAR monthly active developers / sum over peer chains, 2027-Q3 (Electric Capital, dev_ecosystem_share_quarterly.csv)",
                ">=", float(n["near_to_peer_set"].min()), "ratio", LONG, float(n["near_to_peer_set"][-1]),
                n["quarter"][-1], "make refresh; near_to_peer_set", "lowest of the last four quarters")
    nv = mm["model_multiples_near_vs_peers"]
    r = nv.filter((pl.col("variant") == "fees_plus_intents_fees") & (pl.col("basis") == "30d_annualized"))
    if r.height:
        r = r.row(0, named=True)
        add("P7", "Q7", "Counting Intents, NEAR stays cheaper than the median peer per dollar of fees",
            "NEAR market cap / annualized (chain fees + Intents fees), 30 days to 2027-04-30, vs the peer median at "
            "that date (model_multiples_near_vs_peers.csv)", "<=", r["peer_median"], "multiple", SHORT,
            r["near_multiple"], r.get("as_of") or as_of, "make refresh; near_multiple vs peer_median",
            "the peer median multiple (re-measured at the check date)")
    return pl.DataFrame(rows, infer_schema_length=None)
