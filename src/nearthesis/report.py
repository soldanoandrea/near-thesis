"""Render reports/metrics_summary.md from pipeline outputs. Every number printed here comes from a DataFrame."""

from __future__ import annotations

import polars as pl

GRADES = "A = on-chain, re-runnable from chain data; B = aggregator (NearBlocks, DefiLlama, CoinGecko, Blockscout)."


def fmt(v, unit: str = "") -> str:
    if v is None:
        return "n/a"
    if isinstance(v, bool):
        return "yes" if v else "no"
    if unit in ("ratio", "ratio/yr"):
        return f"{v * 100:.2f}%"
    if unit == "USD":
        a = abs(v)
        if a >= 1e9:
            return f"${v / 1e9:,.2f}B"
        if a >= 1e6:
            return f"${v / 1e6:,.2f}M"
        if a >= 1e3:
            return f"${v / 1e3:,.1f}k"
        return f"${v:,.2f}"
    if unit == "NEAR":
        return f"{v / 1e6:,.2f}M NEAR" if abs(v) >= 1e6 else f"{v:,.0f} NEAR"
    if isinstance(v, float) and abs(v) < 100 and v != int(v):
        return f"{v:,.3f}"
    return f"{v:,.0f}"


def table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "/") for c in r) + " |" for r in rows]
    return "\n".join(out)


def _ci(r: dict) -> str:
    if r.get("ci90_low") is None or r.get("ci90_high") is None:
        return ""
    return f"{fmt(r['ci90_low'], r['unit'])} to {fmt(r['ci90_high'], r['unit'])}"


def console_table(fp: pl.DataFrame) -> str:
    lines = ["Key results (first pass)", "-" * 100]
    for r in fp.iter_rows(named=True):
        ci = _ci(r)
        lines.append(f"{r['question']:<3} {r['label'][:70]:<70} {fmt(r['value'], r['unit']):>16}"
                     + (f"  [90% CI {ci}]" if ci else ""))
    return "\n".join(lines)


def render(*, m: dict, as_of: str, as_of_peers: str, fp: pl.DataFrame, epochs: pl.DataFrame, act: dict,
           peers: pl.DataFrame, cov: pl.DataFrame, events: pl.DataFrame, bvf: pl.DataFrame, conc: pl.DataFrame) -> str:
    files = m["files"]
    fetched = sorted(v["fetched_at_utc"] for v in files.values())
    rows_total = sum(v["rows"] for v in files.values())
    L: list[str] = []
    L.append("# NEAR thesis: first-pass metrics (phase 1)")
    L.append("")
    L.append("Generated by `make reproduce` from the committed snapshots in `data/raw/`. Do not edit by hand: every "
             "number below is computed by `src/nearthesis/` and also written to `data/processed/metrics_first_pass.csv`.")
    L.append("")
    L.append(table(["Snapshot", "Value"], [
        ["As-of date (last complete UTC day)", as_of],
        ["As-of date for cross-chain comparisons", as_of_peers],
        ["Raw files / rows", f"{len(files)} / {rows_total:,}"],
        ["Fetched (UTC)", f"{fetched[0]} to {fetched[-1]}"],
    ]))
    L.append("")
    L.append(f"Evidence grades: {GRADES} Not financial advice.")
    L.append("")

    for q, title in (("Q1", "Q1. Is the activity real? (activity and its composition)"),
                     ("Q2", "Q2. NEAR Intents (DefiLlama, single-sourced from NEAR-uploaded Dune data)"),
                     ("Q3", "Q3. AI / chain-abstraction footprint (census counts)"),
                     ("Q4", "Q4. Supply: issuance, burn, staking, treasuries"),
                     ("Q5", "Q5. Fees and value accrual"),
                     ("Q7", "Q7. Comparables (headline; full table below)")):
        sub = fp.filter(pl.col("question") == q)
        if not sub.height:
            continue
        L.append(f"## {title}")
        L.append("")
        L.append(table(["Metric", "Value", "90% CI", "Window", "Source", "Grade"],
                       [[r["label"], fmt(r["value"], r["unit"]), _ci(r), r["window"], r["source"], r["grade"]]
                        for r in sub.iter_rows(named=True)]))
        notes = [f"- {r['label']}: {r['notes']}" for r in sub.iter_rows(named=True) if r["notes"]]
        if notes:
            L.append("")
            L += notes
        L.append("")

    # supply by year
    L.append("## Supply accounting by year (sampled epochs, archival block headers)")
    L.append("")
    y = (epochs.with_columns(pl.col("start_date").str.slice(0, 4).alias("year")).group_by("year")
         .agg(pl.len().alias("n"), pl.col("max_inflation_rate").drop_nulls().last().alias("cap"),
              pl.col("mint_annualized_rate").mean().alias("mint"), pl.col("burn_annualized_rate").mean().alias("burn"),
              pl.col("net_annualized_rate").mean().alias("net"),
              (pl.col("burn_near").sum() / pl.col("mint_next_near").sum()).alias("burn_to_mint"),
              pl.col("staking_ratio").drop_nulls().mean().alias("staking"),
              pl.col("num_validators").drop_nulls().mean().alias("vals"),
              pl.col("nakamoto_coefficient").drop_nulls().mean().alias("nak"),
              pl.col("block_identity_holds").drop_nulls().mean().alias("ident"))
         .sort("year"))
    L.append(table(["Year", "Epochs sampled", "Cap (end of year)", "Issuance /yr", "Burn /yr", "Net /yr",
                    "Burn / mint", "Staking ratio", "Validators", "Nakamoto", "Identity holds"],
                   [[r["year"], r["n"], fmt(r["cap"], "ratio"), fmt(r["mint"], "ratio"), fmt(r["burn"], "ratio"),
                     fmt(r["net"], "ratio"), fmt(r["burn_to_mint"], "ratio"), fmt(r["staking"], "ratio"),
                     fmt(r["vals"]), fmt(r["nak"]), fmt(r["ident"], "ratio")] for r in y.iter_rows(named=True)]))
    L.append("")
    L.append("Issuance = NEAR minted on the first block of the next epoch, annualized with nearcore's 365-day year; "
             "burn = supply decrease inside the epoch. Staking ratio = stake of the epoch's validator set / total "
             "supply (empty before epoch 545, where archival nodes no longer serve `validators`).")
    L.append("")
    if events.height:
        L.append(table(["max_inflation_rate change", "Last sample before", "First sample after"],
                       [[f"{fmt(r['from_rate'], 'ratio')} -> {fmt(r['to_rate'], 'ratio')}",
                         r["last_sample_before_utc"], r["first_sample_after_utc"]] for r in events.iter_rows(named=True)]))
        L.append("")

    # activity by quarter
    L.append("## Activity composition by quarter (last 8 quarters)")
    L.append("")
    mon = act["monthly"].with_columns(
        (pl.col("month").str.slice(0, 4) + "-Q" + ((pl.col("month").str.slice(5, 2).cast(pl.Int64) - 1) // 3 + 1)
         .cast(pl.Utf8)).alias("quarter"))
    qc = (mon.group_by("quarter").agg(pl.col("nb_txns").sum(), pl.col("nb_days").sum(),
                                      pl.col("census_game_hot_tg").sum(), pl.col("census_tracked_total").sum(),
                                      pl.col("organic_proxy_txns").sum(), pl.col("is_partial_month").any())
          .join(act["quarterly"], on="quarter", how="left").sort("quarter").tail(8))
    L.append(table(["Quarter", "Txs/day (NearBlocks)", "HOT share (census)", "5 tracked contracts (census)",
                    "Relayed (sample, 90% CI)", "Implicit signers (sample, 90% CI)", "Organic proxy txs/day"],
                   [[r["quarter"] + (" (partial)" if r["is_partial_month"] else ""),
                     fmt(r["nb_txns"] / r["nb_days"]), fmt(r["census_game_hot_tg"] / r["nb_txns"], "ratio"),
                     fmt(r["census_tracked_total"] / r["nb_txns"], "ratio"),
                     f"{fmt(r['relayed_share'], 'ratio')} ({fmt(r['relayed_share_p05'], 'ratio')} to {fmt(r['relayed_share_p95'], 'ratio')})",
                     f"{fmt(r['implicit_signer_share'], 'ratio')} ({fmt(r['implicit_signer_share_p05'], 'ratio')} to {fmt(r['implicit_signer_share_p95'], 'ratio')})",
                     fmt(r["organic_proxy_txns"] / r["nb_days"]) if r["organic_proxy_txns"] is not None else "n/a"]
                    for r in qc.iter_rows(named=True)]))
    L.append("")
    L.append("Census = exact FastNear counts of transactions whose real receiver is the contract, divided by NearBlocks "
             "transactions. Sample = all transactions of 30 random blocks per month. Organic proxy = transactions to "
             "non-tracked contracts that are neither relayed nor signed by implicit accounts. It is a structural "
             "proxy, not a bot score; the per-signer bot score is phase 2.")
    L.append("")

    # peers
    L.append(f"## Comparables as of {as_of_peers}")
    L.append("")
    L.append(table(["Chain", "Market cap", "TVL", "Stablecoins", "Chain fees 30d", "DEX volume 30d",
                    "Fees (30d ann.) / mcap", "TVL / mcap", "DEX 30d / TVL", "Fees 30d YoY", "TVL YoY"],
                   [[r["chain"], fmt(r["market_cap_usd"], "USD"), fmt(r["tvl_usd"], "USD"), fmt(r["stablecoins_usd"], "USD"),
                     fmt(r["chain_fees_30d_usd"], "USD"), fmt(r["dex_volume_30d_usd"], "USD"),
                     fmt(r["fees_30d_annualized_to_mcap"], "ratio"), fmt(r["tvl_to_mcap"], "ratio"),
                     fmt(r["dex_volume_30d_to_tvl"], "ratio"), fmt(r["chain_fees_30d_yoy"], "ratio"),
                     fmt(r["tvl_yoy"], "ratio")] for r in peers.iter_rows(named=True)]))
    L.append("")
    L.append("Market caps: CoinGecko (keyless, 365 days). Base has no native token, so its ratios are n/a. NEAR's DEX "
             "volume on DefiLlama includes NEAR Intents (cross-chain swaps settled on NEAR); see the ex-Intents line in Q7.")
    L.append("")

    # active users definitions (pipeline numbers only)
    L.append("## \"Active users\": what each pipeline number counts")
    L.append("")
    au = fp.filter(pl.col("metric_id").is_in(["q1.active_accounts_30d_avg", "q1.aurora_active_accounts_30d_avg"]))
    defs = {"q1.active_accounts_30d_avg": "NearBlocks `active_accounts`: distinct accounts active per UTC day on NEAR "
                                          "(NearBlocks definition, not documented in detail).",
            "q1.aurora_active_accounts_30d_avg": "Blockscout `activeAccounts` on Aurora: distinct EVM addresses sending "
                                                 "transactions per day. Separate address space; not additive with NEAR."}
    L.append(table(["Metric", "Value", "Definition"],
                   [[r["label"], fmt(r["value"], r["unit"]), defs[r["metric_id"]]] for r in au.iter_rows(named=True)]))
    L.append("")
    L.append("Third-party figures (Artemis DAU, Nansen daily signers) are not fetched by this pipeline; see "
             "`docs/DATA_NOTES.md` for the reconciliation table.")
    L.append("")

    # coverage
    L.append("## Series coverage (gaps are reported, never filled)")
    L.append("")
    gaps = cov.filter((pl.col("missing_days") > 0) | (pl.col("null_values") > 0)).sort(["chain", "metric", "source"])
    L.append(f"{cov.height} daily series; {gaps.height} have missing days or null values:")
    L.append("")
    if gaps.height:
        L.append(table(["Chain", "Metric", "Source", "First", "Last", "Missing days", "Nulls", "Longest gap (days)"],
                       [[r["chain"], r["metric"], r["source"], r["first_date"], r["last_date"], r["missing_days"],
                         r["null_values"], r["longest_gap_days"]] for r in gaps.iter_rows(named=True)]))
        L.append("")
    L.append("Validator concentration per sampled epoch is in `data/processed/validator_concentration.csv`; "
             "exact burn vs prorated NearBlocks fees per epoch in `data/processed/burn_vs_fees_epochs.csv`.")
    L.append("")
    return "\n".join(L)
