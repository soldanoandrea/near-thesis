"""thesis/ documents quote numbers only as the pipeline prints them: every "`metric_id` = value" in thesis/priors.md
must equal the formatted value in data/processed/metrics_phase2.csv or metrics_first_pass.csv."""

import re

import polars as pl

from nearthesis import paths
from nearthesis.report import fmt

QUOTE = re.compile(r"`([a-z0-9]+\.[A-Za-z0-9_.]+)` = (-?\d[\d,]*(?:\.\d+)?(?:%|M NEAR| NEAR)?)")


def _metrics() -> dict[str, str]:
    out = {}
    for name in ("metrics_phase2.csv", "metrics_first_pass.csv"):
        df = pl.read_csv(paths.PROCESSED / name, infer_schema_length=None)
        for r in df.iter_rows(named=True):
            out[r["metric_id"]] = fmt(r["value"], r["unit"])
    return out


def test_priors_quotes_match_generated_metrics():
    text = (paths.ROOT / "thesis" / "priors.md").read_text()
    quotes = QUOTE.findall(text)
    assert quotes, "priors.md should quote the metrics it relies on"
    m = _metrics()
    for mid, val in quotes:
        assert mid in m, f"{mid} is not a generated metric"
        assert m[mid] == val, f"{mid}: priors.md says {val}, pipeline prints {m[mid]}"


def test_falsifiers_document_is_generated():
    text = (paths.ROOT / "thesis" / "falsifiers.md").read_text()
    assert "Generated by `make reproduce`" in text
    assert re.search(r"sha256 of `data/processed/predictions.csv`: `[0-9a-f]{64}`", text)
    pred = pl.read_csv(paths.PROCESSED / "predictions.csv", infer_schema_length=None)
    assert set(pred["question"]) >= {"Q1", "Q2", "Q3", "Q4", "Q5", "Q6", "Q7"}
    assert pred["threshold"].null_count() == 0 and pred["check_date"].null_count() == 0
